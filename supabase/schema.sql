-- Run this once in your Supabase project's SQL Editor (Project -> SQL Editor -> New query).

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  play_date date not null,
  won boolean not null default false,
  guesses_used int not null default 0,
  score int not null default 0,
  created_at timestamptz not null default now(),
  unique (name, play_date)
);

create index if not exists leaderboard_play_date_score_idx
  on public.leaderboard (play_date, score desc);

-- Row Level Security is enabled with no public policies: only requests using the
-- service-role key (used exclusively inside Netlify Functions, never shipped to
-- the browser) can read or write this table. The anon/public key cannot touch it.
alter table public.leaderboard enable row level security;
